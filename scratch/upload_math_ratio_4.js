async function upload() {
  console.log('Uploading study notes for math_ratio_4 (Mixture and Alligation)...');
  const sanitized = sanitizeForFirestore(topicNotesData);
  await db.collection('topic_study_notes').doc('cgv_master_math_ratio_4').set(sanitized);
  console.log('✅ cgv_master_math_ratio_4 saved to Firestore topic_study_notes!');

  // Sync cache: syllabi_custom_all.json
  const cachePath = path.resolve(__dirname, '../server/data_cache/syllabi_custom_all.json');
  if (fs.existsSync(cachePath)) {
    const syllabi = JSON.parse(fs.readFileSync(cachePath, 'utf8'));
    const cgv = syllabi.find(s => s.id === 'cgv_master');
    if (cgv) {
      let matched = false;
      cgv.subjects.forEach(sub => {
        sub.chapters.forEach(ch => {
          ch.topics.forEach(t => {
            if (t.id === 'math_ratio_4') {
              t.hasStudyNotes = true;
              matched = true;
            }
          });
        });
      });
      if (matched) {
        fs.writeFileSync(cachePath, JSON.stringify(syllabi, null, 2), 'utf8');
        console.log('✅ syllabi_custom_all.json updated: math_ratio_4 hasStudyNotes = true');
      }
    }
  }

  console.log('\nUpload complete! 🚀');
}

upload().then(() => process.exit(0)).catch(err => {
  console.error(err);
  process.exit(1);
});
