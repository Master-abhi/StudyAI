async function upload() {
  console.log('Uploading study notes for math_men_2 (3D Mensuration)...');
  const sanitized = sanitizeForFirestore(topicNotesData);
  await db.collection('topic_study_notes').doc('cgv_master_math_men_2').set(sanitized);
  console.log('✅ cgv_master_math_men_2 saved to Firestore topic_study_notes!');

  // Sync syllabi in Firestore
  const docRef = db.collection('syllabi').doc('cgv_master');
  const doc = await docRef.get();
  if (doc.exists) {
    const data = doc.data();
    let updated = false;
    data.subjects.forEach(sub => {
      sub.chapters.forEach(ch => {
        ch.topics.forEach(t => {
          if (t.id === 'math_men_2') {
            t.hasStudyNotes = true;
            updated = true;
          }
        });
      });
    });
    if (updated) {
      await docRef.set(data);
      console.log('✅ syllabi/cgv_master updated: math_men_2 hasStudyNotes = true');
    }
  }

  console.log('\nUpload complete! 🚀');
}

