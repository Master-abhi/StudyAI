async function uploadTopic() {
  try {
    const docId = `cgv_master_${studyNotesData.topicId}`;
    const sanitized = sanitizeForFirestore(studyNotesData);
    await db.collection('topic_study_notes').doc(docId).set(sanitized);
    console.log(`[Uploaded] topic_study_notes/${docId} successfully written.`);
    await markTopicCompleted(studyNotesData.subjectId, studyNotesData.chapterId, studyNotesData.topicId);
    process.exit(0);
  } catch (err) {
    console.error('Error uploading:', err);
    process.exit(1);
  }
}

uploadTopic();
