async function uploadBatch() {
  const examId = 'cgv_master';
  const topicIds = Object.keys(batchData);

  for (const topicId of topicIds) {
    const docId = `${examId}_${topicId}`;
    console.log(`Uploading ${docId}...`);
    const sanitized = sanitizeForFirestore(batchData[topicId]);

    await db.collection('topic_study_notes').doc(docId).set({
      examId,
      topicId,
      studyNotes: sanitized,
      updatedAt: new Date().toISOString()
    });
    console.log(`✅ Saved ${docId}`);
  }

  // Update syllabi flags
  const sylRef = db.collection('syllabi').doc(examId);
  const sylSnap = await sylRef.get();
  if (sylSnap.exists) {
    const sylData = sylSnap.data();
    for (const sub of sylData.subjects || []) {
      for (const ch of sub.chapters || []) {
        for (const top of ch.topics || []) {
          if (batchData[top.id]) {
            top.hasStudyNotes = true;
            top.notesUpdatedAt = new Date().toISOString();
            if (top.studyNotes) delete top.studyNotes;
          }
        }
      }
    }
    await sylRef.set(sylData);
    console.log(`✅ Syllabi flags updated for ${topicIds.join(', ')}`);
  }
  console.log(`🎉 Batch upload completed for ${topicIds.join(', ')}`);
  process.exit(0);
}

uploadBatch().catch(err => {
  console.error('Batch upload error:', err);
  process.exit(1);
});
