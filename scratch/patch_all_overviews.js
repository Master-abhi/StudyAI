async function patchOverviews() {
  console.log('Starting patch for 17 documents...');
  for (const [docId, ov] of Object.entries(overviews)) {
    const docRef = db.collection('topic_study_notes').doc(docId);
    const docSnap = await docRef.get();
    if (!docSnap.exists) {
      console.warn(`Doc ${docId} does not exist in Firestore!`);
      continue;
    }
    const data = docSnap.data();
    const updatedNotes = {
      ...data.studyNotes,
      overview: ov
    };
    await docRef.update({
      studyNotes: updatedNotes,
      updatedAt: new Date().toISOString()
    });
    console.log(`✅ Patched overview for ${docId}`);
  }
  console.log('All 17 documents patched successfully!');
}

patchOverviews().catch(err => {
  console.error('Patch error:', err);
  process.exit(1);
});
