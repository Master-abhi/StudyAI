async function uploadTopic() {
  const topicId = 'cg_cul_8';
  const examId = 'cgv_master';
  const docId = `${examId}_${topicId}`;

  console.log(`Starting upload for ${topicId}...`);
  const sanitized = sanitizeForFirestore(studyNotes_cg_cul_8);

  await db.collection('topic_study_notes').doc(docId).set({
    examId,
    topicId,
    studyNotes: sanitized,
    updatedAt: new Date().toISOString()
  });
  console.log(`✅ Saved ${docId} to topic_study_notes`);

  // Update syllabi doc
  const sylRef = db.collection('syllabi').doc(examId);
  const sylSnap = await sylRef.get();
  if (sylSnap.exists) {
    const sylData = sylSnap.data();
    let found = false;
    for (const sub of sylData.subjects || []) {
      for (const ch of sub.chapters || []) {
        for (const top of ch.topics || []) {
          if (top.id === topicId) {
            top.hasStudyNotes = true;
            top.notesUpdatedAt = new Date().toISOString();
            if (top.studyNotes) delete top.studyNotes;
            found = true;
          }
        }
      }
    }
    if (found) {
      await sylRef.set(sylData);
      console.log(`✅ Syllabi status updated for ${topicId}`);
    }
  }
  console.log(`🎉 ${topicId} upload successfully completed!`);
  process.exit(0);
}

uploadTopic().catch(err => {
  console.error('Upload failed:', err);
  process.exit(1);
});
