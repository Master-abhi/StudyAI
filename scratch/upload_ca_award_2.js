async function upload() {
  try {
    const topicId = 'ca_award_2';
    const docId = `cgv_master_${topicId}`;
    const sanitized = sanitizeForFirestore(studyNotesData);

    const fullPayload = {
      ...sanitized,
      examId: 'cgv_master',
      updatedAt: new Date().toISOString(),
      studyNotes: sanitized
    };

    await db.collection('topic_study_notes').doc(docId).set(fullPayload);
    console.log(`[Uploaded] topic_study_notes/${docId} successfully written with dual root & studyNotes wrapper.`);

    const syllabusRef = db.collection('syllabi').doc('cgv_master');
    const syllabusDoc = await syllabusRef.get();
    if (syllabusDoc.exists) {
      const data = syllabusDoc.data();
      let updated = false;
      for (const sub of data.subjects || []) {
        if (sub.id === 'cgv_master_sub_8') {
          for (const ch of sub.chapters || []) {
            if (ch.id === 'cgv_master_sub_8_ch_8') {
              for (const top of ch.topics || []) {
                if (top.id === topicId) {
                  top.hasStudyNotes = true;
                  updated = true;
                }
              }
            }
          }
        }
      }
      if (updated) {
        await syllabusRef.set(data);
        console.log(`[Syllabus Synced] hasStudyNotes: true for ${topicId}`);
      }
    }
    console.log(`Topic ${topicId} (International Awards) completed successfully!`);
  } catch (err) {
    console.error('Error uploading:', err);
    process.exit(1);
  }
}

upload();
