async function uploadNotes() {
  const examId = 'cgv_master';
  const topicId = 'cg_geo_3';
  const docId = `${examId}_${topicId}`;

  console.log(`Starting updated upload with structured tables for topic: ${topicId}...`);

  const cleanNotes = sanitizeForFirestore(studyNotes);

  // 1. Upload to topic_study_notes collection
  await db.collection('topic_study_notes').doc(docId).set({
    examId,
    topicId,
    studyNotes: cleanNotes,
    updatedAt: new Date().toISOString()
  });
  console.log(`✅ Successfully saved structured tables to topic_study_notes doc: ${docId}`);

  // 2. Ensure syllabi/cgv_master document topic status is updated
  const syllabusRef = db.collection('syllabi').doc(examId);
  const snap = await syllabusRef.get();
  if (snap.exists) {
    const data = snap.data();
    let found = false;
    if (data.subjects) {
      data.subjects.forEach(s => {
        if (s.chapters) {
          s.chapters.forEach(c => {
            if (c.topics) {
              c.topics.forEach(t => {
                if (t.id === topicId) {
                  t.hasStudyNotes = true;
                  t.notesUpdatedAt = new Date().toISOString();
                  found = true;
                }
              });
            }
          });
        }
      });
    }
    if (found) {
      data.updatedAt = new Date().toISOString();
      await syllabusRef.set(data);
      console.log(`✅ Syllabi status refreshed for ${topicId}`);
    }
  }

  console.log('🎉 Done! Tables are now completely structured according to TopicNotesReaderModal schema.');
}

uploadNotes().catch(err => {
  console.error('Upload Error:', err);
  process.exit(1);
});
