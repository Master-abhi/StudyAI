async function uploadNotes() {
  console.log('Uploading study notes for Semiconductors (phy_14)...');

  // 1. Write to Firestore
  await db.collection('topic_study_notes').doc('cgv_master_phy_14').set(topicNotesData, { merge: true });
  console.log('Successfully written to Firestore: topic_study_notes/cgv_master_phy_14! ✅');

  // 2. Update local syllabi cache
  const cachePath = path.resolve(__dirname, '../server/data_cache/syllabi_custom_all.json');
  if (fs.existsSync(cachePath)) {
    try {
      const cacheData = JSON.parse(fs.readFileSync(cachePath, 'utf8'));
      let cacheUpdated = false;
      if (Array.isArray(cacheData)) {
        cacheData.forEach(s => {
          if (s.id === 'cgv_master') {
            s.subjects.forEach(sub => {
              if (sub.id === 'cgv_master_sub_2') {
                sub.chapters.forEach(ch => {
                  ch.topics.forEach(t => {
                    if (t.id === 'phy_14') {
                      t.hasStudyNotes = true;
                      cacheUpdated = true;
                    }
                  });
                });
              }
            });
          }
        });
      }
      if (cacheUpdated) {
        fs.writeFileSync(cachePath, JSON.stringify(cacheData, null, 2), 'utf8');
        console.log('Updated local syllabi_custom_all.json cache! ✅');
      }
    } catch (e) {
      console.error('Error updating cache:', e.message);
    }
  }

  // 3. Verification read
  const snap = await db.collection('topic_study_notes').doc('cgv_master_phy_14').get();
  if (snap.exists) {
    const d = snap.data();
    console.log('\nVerification:');
    console.log('- Topic Title (Hi):', d.studyNotes?.titleHi);
    console.log('- Chapters count:', d.studyNotes?.chapters?.length);
    console.log('- Chapter 1 title:', d.studyNotes?.chapters[0]?.title);
    console.log('- Comparative Tables:', d.studyNotes?.comparativeTables?.length);
    console.log('- PYQs:', d.studyNotes?.pyqs?.length);
    console.log('- MCQs:', d.studyNotes?.mcqs?.length);
    console.log('- Key Terms:', d.studyNotes?.keyTerminology?.length);
    console.log('- Sources:', d.studyNotes?.sources?.length);
    console.log('- Confusion Buster:', d.studyNotes?.confusionBuster?.length);
    console.log('- FAQs:', d.studyNotes?.faqList?.length);
  }
}

