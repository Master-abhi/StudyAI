async function uploadNotes() {
  console.log('Uploading notes for ind_misc_4: Important Days and Themes (महत्वपूर्ण दिवस)...');
  await db.collection('topic_study_notes').doc('cgv_master_ind_misc_4').set(topicNotesData);
  console.log('Successfully uploaded cgv_master_ind_misc_4 to Firestore! ✅');

  // Also update syllabus cgv_master so hasStudyNotes: true for ind_misc_4
  const syllabusSnap = await db.collection('syllabi').doc('cgv_master').get();
  if (syllabusSnap.exists) {
    const syllabus = syllabusSnap.data();
    let updated = false;
    (syllabus.subjects || []).forEach(sub => {
      (sub.chapters || []).forEach(ch => {
        (ch.topics || []).forEach(t => {
          if (t.id === 'ind_misc_4') {
            t.hasStudyNotes = true;
            updated = true;
            console.log('Marked ind_misc_4 hasStudyNotes: true in syllabus');
          }
        });
      });
    });

    if (updated) {
      await db.collection('syllabi').doc('cgv_master').set(syllabus);
      console.log('Updated cgv_master syllabus document in Firestore! ✅');
    }
  }

  // Verification read
  const snap = await db.collection('topic_study_notes').doc('cgv_master_ind_misc_4').get();
  if (snap.exists) {
    const d = snap.data();
    console.log('Verification:');
    console.log('- Topic:', d.studyNotes?.titleHi);
    console.log('- Chapters count:', d.studyNotes?.chapters?.length);
    console.log('- Comparative Tables:', d.studyNotes?.comparativeTables?.length);
    console.log('- PYQs:', d.studyNotes?.pyqs?.length);
    console.log('- MCQs:', d.studyNotes?.mcqs?.length);
    console.log('- One-Liner Revision items:', d.studyNotes?.oneLinerRevision?.length);
    console.log('- Rapid Revision items:', d.studyNotes?.rapidRevision?.length);
  }
}

uploadNotes()
  .then(() => process.exit(0))
  .catch(err => {
    console.error('Upload Error:', err);
    process.exit(1);
  });
