async function uploadNotes() {
  try {
    const docRef = db.collection('topic_study_notes').doc('cgv_master_env_4');
    await docRef.set(topicNotesData);
    console.log('Successfully uploaded study notes for cgv_master_env_4');

    // Update syllabus cache
    const cachePath = path.join(__dirname, '../server/data_cache/syllabi_custom_all.json');
    if (fs.existsSync(cachePath)) {
      const data = JSON.parse(fs.readFileSync(cachePath, 'utf8'));
      const cgv = data.find(s => s.id === 'cgv_master');
      if (cgv) {
        const sub2 = cgv.subjects.find(sub => sub.id === 'cgv_master_sub_2');
        if (sub2) {
          const ch4 = sub2.chapters.find(c => c.id === 'cgv_master_sub_2_ch_4');
          if (ch4) {
            const topic = ch4.topics.find(t => t.id === 'env_4');
            if (topic) {
              topic.hasStudyNotes = true;
              fs.writeFileSync(cachePath, JSON.stringify(data, null, 2), 'utf8');
              console.log('Updated cache for env_4 hasStudyNotes: true');
            }
          }
        }
      }
    }
  } catch (error) {
    console.error('Error uploading study notes:', error);
    process.exit(1);
  }
}

uploadNotes();
