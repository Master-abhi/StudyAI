async function uploadGeo5() {
  const examId = 'cgv_master';
  const topicId = 'cg_geo_5';
  const docId = `${examId}_${topicId}`;

  console.log(`Starting upload for ${topicId}...`);
  const cleanNotes = sanitizeForFirestore(geo5Notes);

  await db.collection('topic_study_notes').doc(docId).set({
    examId,
    topicId,
    studyNotes: cleanNotes,
    updatedAt: new Date().toISOString()
  });
  console.log(`✅ Saved ${docId} to topic_study_notes`);

  const syllabusRef = db.collection('syllabi').doc(examId);
  const snap = await syllabusRef.get();
  if (snap.exists) {
    const data = snap.data();
    let found = false;
    if (data.subjects) {
      data.subjects.forEach(s => {
        if (s.chapters) {
          s.chapters.forEach(c => {
            if (c.topics) {
              c.topics.forEach(t => {
                if (t.id === topicId) {
                  t.hasStudyNotes = true;
                  t.notesUpdatedAt = new Date().toISOString();
                  found = true;
                }
              });
            }
          });
        }
      });
    }
    if (found) {
      data.updatedAt = new Date().toISOString();
      await syllabusRef.set(data);
      console.log(`✅ Syllabi status updated for ${topicId}`);
    }
  }

  console.log(`🎉 ${topicId} upload successfully completed!`);
}

uploadGeo5().catch(err => {
  console.error('Error in uploadGeo5:', err);
  process.exit(1);
});
