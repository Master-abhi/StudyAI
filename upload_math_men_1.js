async function uploadTopic() {
  console.log('Uploading comprehensive study notes for math_men_1 (2D Mensuration)...');
  const docRef = db.collection('topic_study_notes').doc('cgv_master_math_men_1');
  await docRef.set({
    examId: 'cgv_master',
    topicId: 'math_men_1',
    studyNotes: math_men_1_notes,
    updatedAt: new Date().toISOString()
  });
  console.log('Updated topic_study_notes/cgv_master_math_men_1 successfully.');

  const syllabusRef = db.collection('syllabi').doc('cgv_master');
  const snap = await syllabusRef.get();
  if (snap.exists) {
    const data = snap.data();
    let updated = false;
    if (Array.isArray(data.subjects)) {
      data.subjects.forEach(sub => {
        if (Array.isArray(sub.chapters)) {
          sub.chapters.forEach(ch => {
            if (Array.isArray(ch.topics)) {
              ch.topics.forEach(t => {
                if (t.id === 'math_men_1') {
                  t.hasStudyNotes = true;
                  updated = true;
                }
              });
            }
          });
        }
      });
    }
    if (updated) {
      await syllabusRef.update({ subjects: data.subjects });
      console.log('Updated syllabus flag hasStudyNotes=true for math_men_1.');
    }
  }

  try {
    invalidateCache('syllabi/cgv_master');
    invalidateCache('topic_study_notes/cgv_master_math_men_1');
    console.log('Cache cleared successfully.');
  } catch (err) {
    console.log('Cache invalidate notice:', err.message);
  }
}

uploadTopic()
  .then(() => process.exit(0))
  .catch(err => {
    console.error('Upload failed:', err);
    process.exit(1);
  });
