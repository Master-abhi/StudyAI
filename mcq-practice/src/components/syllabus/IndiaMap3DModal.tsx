function geojsonPolygonToShapes(coords: any, isMulti: boolean): { shapes: THREE.Shape[]; centroid: [number, number]; outerRing: [number, number][] } {
  const shapes: THREE.Shape[] = [];
  const polyList = isMulti ? coords : [coords];
  let maxRingLen = 0;
  let primaryRing: [number, number][] = [];

  polyList.forEach((poly: any) => {
    if (!poly || poly.length === 0) return;
    const outerRing = poly[0];
    if (!outerRing || outerRing.length < 3) return;

    if (outerRing.length > maxRingLen) {
      maxRingLen = outerRing.length;
      primaryRing = outerRing;
    }

    const shape = new THREE.Shape();
    outerRing.forEach(([lon, lat]: [number, number], idx: number) => {
      const [x, y] = lonLatToXY(lon, lat);
      if (idx === 0) shape.moveTo(x, y);
      else shape.lineTo(x, y);
    });
    shape.closePath();

    for (let h = 1; h < poly.length; h++) {
      const holeRing = poly[h];
      if (holeRing && holeRing.length >= 3) {
        const holePath = new THREE.Path();
        holeRing.forEach(([lon, lat]: [number, number], idx: number) => {
          const [x, y] = lonLatToXY(lon, lat);
          if (idx === 0) holePath.moveTo(x, y);
          else holePath.lineTo(x, y);
        });
        holePath.closePath();
        shape.holes.push(holePath);
      }
    }

    shapes.push(shape);
  });

  let sx = 0, sy = 0;
  if (primaryRing.length) {
    primaryRing.forEach(([ln, lt]) => { sx += ln; sy += lt; });
    sx /= primaryRing.length;
    sy /= primaryRing.length;
  } else {
    sx = 82.0; sy = 22.5;
  }

  return { shapes, centroid: [sx, sy], outerRing: primaryRing };
}

function clipPolygonByHalfPlane(poly: [number, number][], nx: number, ny: number, c: number): [number, number][] {
  const out: [number, number][] = [];
  for (let i = 0; i < poly.length; i++) {
    const A = poly[i];
    const B = poly[(i + 1) % poly.length];
    const dA = A[0] * nx + A[1] * ny - c;
    const dB = B[0] * nx + B[1] * ny - c;
    if (dA <= 0) out.push(A);
    if ((dA < 0 && dB > 0) || (dA > 0 && dB < 0)) {
      const t = dA / (dA - dB);
      out.push([A[0] + t * (B[0] - A[0]), A[1] + t * (B[1] - A[1])]);
    }
  }
  return out;
}

