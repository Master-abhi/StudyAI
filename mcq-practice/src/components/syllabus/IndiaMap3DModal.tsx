// Helper: Projection scaling
function lonLatToXY(lon: number, lat: number): [number, number] {
  return [(lon - 82.0) * 1.05, (lat - 22.5) * 1.15];
}

function getPolygonCentroid(coords: [number, number][]): [number, number] {
  let sx = 0, sy = 0;
  coords.forEach(([ln, lt]) => { sx += ln; sy += lt; });
  return [sx / coords.length, sy / coords.length];
}

